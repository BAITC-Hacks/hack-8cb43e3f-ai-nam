def recommendation_text(f: dict[str, Any], units: list[dict[str, Any]], lang: str = "ru") -> str:
    """Текст рекомендации по выводу на выбранном языке ("" — рекомендации для такого вывода нет)."""
    r = R.get(lang, R["ru"])
    t, sub = f["type"], f.get("subtype", "")
    text = ""
    if t == "loss":
        src_unit = f["units"][0] if f["units"] else ""
        nearest = next((e for e in f["evidence"] if e.get("role") == "nearest"), None)
        succ = _successors(units, src_unit)
        target = succ[0] if succ else (nearest.get("unit") if nearest else "")
        fn_text = short(f["evidence"][0].get("text", ""), 140) if f["evidence"] else ""
        text = r["loss_to"].format(fn=fn_text, target=target) if target else r["loss_owner"].format(fn=fn_text)
    elif t == "duplication":
        if len(f["evidence"]) >= 2 and "общей и частной" in f["title"]:
            text = r["dup_shared"]
        else:
            text = r["dup"].format(owner=f["units"][0] if f["units"] else "")
    elif t == "conflict" and sub == "sod":
        text = r["sod"]
    elif t == "conflict" and sub == "dual_subordination":
        text = r["dual"]
    elif t == "conflict" and sub == "declared":
        text = r["declared"]
    elif t == "reorganization":
        if sub == "abolished":
            text = r["abolished"]
        elif sub in ("created", "merged"):
            text = r["created"]
        elif sub in ("reorganized", "split"):
            text = r["reorganized"]
        elif sub == "renamed":
            text = r["renamed"]
    elif t == "requirement_gap":
        nearest = next((e for e in f["evidence"] if e.get("role") == "nearest"), None)
        text = r["req_unit"].format(unit=nearest["unit"]) if nearest and nearest.get("unit") else r["req"]
    elif t == "benchmark":
        text = r["benchmark"]
    if f.get("llm_recommendation"):
        text = f"{text} {r['llm'].format(text=f['llm_recommendation'])}".strip()
    return text


def add_recommendations(result: dict[str, Any]) -> list[dict[str, Any]]:
    units = result["units"]
    recs: list[dict[str, Any]] = []
    for f in result["findings"]:
        text = recommendation_text(f, units)
        if text:
            f["recommendation"] = text
            recs.append({"finding_id": f["id"], "type": f["type"], "severity": f["severity"], "text": text,
                         "units": f.get("units", [])})
    return recs
