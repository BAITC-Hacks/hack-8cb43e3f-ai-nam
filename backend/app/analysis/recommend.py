def _successors(units: list[dict[str, Any]], unit_label: str) -> list[str]:
    for u in units:
        b = u.get("before")
        if not b:
            continue
        label = f"{b['name']} ({b['short']})" if b.get("short") else b["name"]
        if label == unit_label:
            return [f"{a['name']} ({a['short']})" if a.get("short") else a["name"] for a in u.get("after", [])]
    return []


