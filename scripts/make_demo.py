"""Генератор контрольного комплекта документов samples/demo.

Комплект моделирует реорганизацию ИТ-блока АО «ДемоТелеком» с ЗАРАНЕЕ ИЗВЕСТНЫМИ изменениями
(см. samples/README.md и backend/tests/test_demo_scenario.py):

  * реорганизация: Департамент информационных технологий (ДИТ) разделён на Департамент цифровой
    инфраструктуры (ДЦИ) и Службу информационной безопасности (СИБ);
  * переименование: Департамент внутреннего контроля и рисков → Департамент управления рисками и
    внутреннего контроля (функции сохранены);
  * потеря функции: «разработка и актуализация ИТ-стратегии» не передана ни одному подразделению;
  * дублирование: мониторинг исполнения договоров закреплён и за Департаментом закупок, и за Юридическим;
  * конфликт интересов: СИБ и предоставляет права доступа, и проверяет их правомерность.

Форматы подобраны так, чтобы проверить все пути разбора: DOCX (ручная и автоматическая нумерация Word),
PDF, Excel (оргструктура + реестр функций), PNG-схема (распознавание блоков и связей).

Запуск: python scripts/make_demo.py   (нужны python-docx, openpyxl, pillow; для PDF — LibreOffice)
"""
