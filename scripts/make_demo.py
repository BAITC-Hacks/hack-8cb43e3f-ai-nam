def _doc(title_lines: list[str], approval: list[str]) -> Document:
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(12)
    for line in approval:
        p = doc.add_paragraph(line)
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for line in title_lines:
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(line)
        r.bold = True
    return doc


def regulation(path: Path, unit: str, unit_prep: str, abbr: str, parent: str, head: str, edition: str,
               approval: list[str], tasks: list[str], functions: list[str], rights: list[str],
               autonumber: bool = False, extra_sections: list[tuple[str, list[str]]] | None = None) -> None:
    doc = _doc(["ПОЛОЖЕНИЕ", f"о {unit_prep}"], approval)
    p = doc.add_paragraph(f"(редакция № {edition})")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    doc.add_heading("1. Общие положения", level=1)
    doc.add_paragraph(f"1.1. {unit} (далее – {abbr}) является структурным подразделением {COMPANY} "
                      f"(далее – Общество).")
    doc.add_paragraph(f"1.2. {abbr} подчиняется {parent}.")
    doc.add_paragraph(f"1.3. Руководство {abbr} осуществляет {head}, назначаемый на должность приказом "
                      f"Председателя Правления Общества.")
    doc.add_paragraph(f"1.4. В своей деятельности {abbr} руководствуется законодательством Республики Казахстан, "
                      f"Уставом Общества, внутренними нормативными документами и настоящим Положением.")
    doc.add_heading("2. Задачи", level=1)
    for i, t in enumerate(tasks, start=1):
        doc.add_paragraph(f"2.{i}. {t}")
    doc.add_heading("3. Функции", level=1)
    doc.add_paragraph(f"Для выполнения возложенных задач {abbr} осуществляет следующие функции:")
    for i, f in enumerate(functions, start=1):
        if autonumber:
            doc.add_paragraph(f, style="List Number")
        else:
            doc.add_paragraph(f"3.{i}. {f}")
    doc.add_heading("4. Права", level=1)
    doc.add_paragraph(f"{abbr} имеет право:")
    for i, r in enumerate(rights, start=1):
        doc.add_paragraph(f"4.{i}. {r}")
    n = 5
    for title, items in extra_sections or []:
        doc.add_heading(f"{n}. {title}", level=1)
        for i, it in enumerate(items, start=1):
            doc.add_paragraph(f"{n}.{i}. {it}")
        n += 1
    doc.add_heading(f"{n}. Ответственность", level=1)
    doc.add_paragraph(f"{n}.1. Руководитель {abbr} несет ответственность за надлежащее выполнение задач и функций, "
                      f"возложенных на {abbr} настоящим Положением.")
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)


def to_pdf(docx_path: Path) -> Path | None:
    soffice = shutil.which("soffice") or shutil.which("libreoffice")
    if not soffice:
        print("! LibreOffice не найден — PDF не создан, оставлен DOCX", docx_path.name)
        return None
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([soffice, "--headless", "--convert-to", "pdf", "--outdir", tmp, str(docx_path)],
                       check=True, capture_output=True, timeout=180, env={"HOME": tmp, "PATH": "/usr/bin:/bin"})
        pdf = Path(tmp) / (docx_path.stem + ".pdf")
        target = docx_path.with_suffix(".pdf")
        shutil.copy(pdf, target)
    docx_path.unlink()
    return target


